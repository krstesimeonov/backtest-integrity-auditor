"""Write ``audit_returns.csv``, the synthetic input of the quickstart.

The series is invented: 783 weekday returns (2023-01-02 to 2025-12-31) of a
hypothetical strategy, drawn from a seeded Student-t distribution (fat tails)
with a small positive drift. No market data and no real strategy are involved,
so the file can be shared freely and regenerated byte for byte:

    python examples/quickstart/make_audit_returns.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

SEED = 20261102
DESTINATION = Path(__file__).resolve().parent / "audit_returns.csv"


def make_returns() -> pd.DataFrame:
    rng = np.random.default_rng(SEED)
    sessions = pd.bdate_range("2023-01-02", "2025-12-31")
    # Student-t with 4 degrees of freedom, scaled to a 1 % daily volatility.
    shocks = rng.standard_t(4, size=len(sessions)) / np.sqrt(4 / (4 - 2))
    returns = 0.0004 + 0.01 * shocks
    return pd.DataFrame(
        {"timestamp": sessions.strftime("%Y-%m-%d"), "return": returns.round(6)}
    )


if __name__ == "__main__":
    make_returns().to_csv(DESTINATION, index=False, lineterminator="\n")
    print(f"wrote {DESTINATION.name}")
